package com.hotspotmonitor.agent.protocol

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonObject

/* Mirror of shared/src/events.ts (plan 6.2 "Events" row and the watchdog log in 6.5). */

@Serializable
enum class EventKind(val wire: String) {
    /** Service started; data: { reason: 'boot' | 'restart' | 'update' | 'manual' } */
    @SerialName("agent_start") AGENT_START("agent_start"),
    /** Phone booted; data: { boot_count, boot_reason } */
    @SerialName("boot") BOOT("boot"),
    /** Internet up/down; data: { online: boolean, down_for_s? } */
    @SerialName("connectivity") CONNECTIVITY("connectivity"),
    /** Serving cell changed; data: { from: {pci, cell_id, band}, to: {...} } */
    @SerialName("cell_change") CELL_CHANGE("cell_change"),
    /** e.g. LTE -> NR_NSA */
    @SerialName("net_type_change") NET_TYPE_CHANGE("net_type_change"),
    @SerialName("tether_up") TETHER_UP("tether_up"),
    @SerialName("tether_down") TETHER_DOWN("tether_down"),
    @SerialName("usb_connected") USB_CONNECTED("usb_connected"),
    @SerialName("usb_disconnected") USB_DISCONNECTED("usb_disconnected"),
    @SerialName("power_connected") POWER_CONNECTED("power_connected"),
    /** USB power removed (plan 6.5 "USB power lost"). */
    @SerialName("power_lost") POWER_LOST("power_lost"),
    /** Plugged in but battery falling for weak_power_min. */
    @SerialName("weak_power") WEAK_POWER("weak_power"),
    /** Battery >= temp_warn_c. */
    @SerialName("temp_warning") TEMP_WARNING("temp_warning"),
    /** Battery >= temp_stop_charge_c (charging stopped). */
    @SerialName("temp_critical") TEMP_CRITICAL("temp_critical"),
    /** Back below temp_resume_c. */
    @SerialName("temp_normal") TEMP_NORMAL("temp_normal"),
    /** data: { reason: 'limit' | 'heat' | 'manual' } */
    @SerialName("charging_stopped") CHARGING_STOPPED("charging_stopped"),
    @SerialName("charging_resumed") CHARGING_RESUMED("charging_resumed"),
    /** data: { seconds } */
    @SerialName("radio_rest") RADIO_REST("radio_rest"),
    /** data: { rule, action, step, outcome } */
    @SerialName("watchdog_action") WATCHDOG_ACTION("watchdog_action"),
    /** Agent-local command executed (local UI / watchdog); data: CommandRecord-like. */
    @SerialName("command") COMMAND("command"),
    /** Auto-revert happened; data: { command_id, name } */
    @SerialName("revert") REVERT("revert"),
    /** Tilt or location changed; data: { tilt_change_deg, moved_m, lat, lon } */
    @SerialName("moved") MOVED("moved"),
    /** data: { from, body, at } */
    @SerialName("sms_received") SMS_RECEIVED("sms_received"),
    /** Reboot limit reached; data: { source } */
    @SerialName("reboot_blocked") REBOOT_BLOCKED("reboot_blocked"),
    /** Agent applied a new settings version; data: { version } */
    @SerialName("settings_applied") SETTINGS_APPLIED("settings_applied"),
    /** Spot test / speed test finished; data: { spot_id } */
    @SerialName("finder") FINDER("finder"),
    /** Unexpected Agent error; data: { where, message } */
    @SerialName("error") ERROR("error"),
}

@Serializable
enum class Severity(val wire: String) {
    @SerialName("info") INFO("info"),
    @SerialName("warning") WARNING("warning"),
    @SerialName("critical") CRITICAL("critical"),
}

@Serializable
data class AgentEvent(
    /** "e_" + random, generated by the Agent; the Server ignores duplicates. */
    val id: String,
    val ts: String,
    val kind: EventKind,
    val severity: Severity,
    /** Short human-readable line. */
    val message: String,
    val data: JsonObject? = null,
)

/** Alert kinds (settings.ts `AlertKind`), in the order of `ALERT_KINDS`. */
val ALERT_KINDS: List<String> = listOf(
    "offline", "back_online", "weak_power", "low_battery", "hot", "signal_drop", "cell_changed",
    "tether_down", "usb_power_lost", "data_quota", "moved", "watchdog", "carrier_sms", "server_test",
)

/** Events that raise an alert on the Server (events.ts `EVENT_ALERT`). */
val EVENT_ALERT: Map<EventKind, String> = mapOf(
    EventKind.WEAK_POWER to "weak_power",
    EventKind.TEMP_WARNING to "hot",
    EventKind.TEMP_CRITICAL to "hot",
    EventKind.POWER_LOST to "usb_power_lost",
    EventKind.MOVED to "moved",
    EventKind.WATCHDOG_ACTION to "watchdog",
    EventKind.REVERT to "watchdog",
    EventKind.REBOOT_BLOCKED to "watchdog",
    EventKind.SMS_RECEIVED to "carrier_sms",
)
