package com.hotspotmonitor.agent.protocol

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/* Mirror of the types in shared/src/finder.ts (plan section 7). The score formula is in Score.kt. */

@Serializable
enum class FinderMode(val wire: String) {
    @SerialName("idle") IDLE("idle"),
    @SerialName("walk") WALK("walk"),
    @SerialName("spot") SPOT("spot"),
    @SerialName("speed") SPEED("speed"),
    @SerialName("headless") HEADLESS("headless"),
}

@Serializable
data class FinderProgress(
    val label: String,
    @SerialName("elapsed_s") val elapsedS: Int,
    @SerialName("total_s") val totalS: Int,
)

/** Streamed 1/s while a Dashboard has the Finder screen open (plan 7.3 "Mirror"). Not stored. */
@Serializable
data class FinderLive(
    val ts: String,
    val mode: FinderMode,
    /** Smoothed. */
    val score: Double? = null,
    @SerialName("score_raw") val scoreRaw: Double? = null,
    val rsrp: Double? = null,
    val sinr: Double? = null,
    val rsrq: Double? = null,
    @SerialName("net_type") val netType: NetType? = null,
    val band: Int? = null,
    val pci: Int? = null,
    @SerialName("cell_id") val cellId: Long? = null,
    val ta: Int? = null,
    /** Serving-cell changes in the last 5 minutes (plan 7.5). */
    @SerialName("cell_switches_5min") val cellSwitches5min: Int? = null,
    /** Spot / speed test progress. */
    val progress: FinderProgress? = null,
)

@Serializable
data class MetricStats(
    val avg: Double,
    val min: Double,
    val max: Double,
    /** Stability: lower is steadier. */
    val std: Double,
    val samples: Int,
)

@Serializable
data class SpeedRun(
    @SerialName("down_mbps") val downMbps: Double? = null,
    @SerialName("up_mbps") val upMbps: Double? = null,
    @SerialName("ping_ms") val pingMs: Double? = null,
    @SerialName("jitter_ms") val jitterMs: Double? = null,
    /** Total data used by this run. */
    val bytes: Long,
    val at: String,
)

@Serializable
data class SpeedSession(
    val at: String,
    /** Started between 20:00 and 22:00 phone local time (plan 7.4 step 4). */
    @SerialName("peak_hour") val peakHour: Boolean,
    val runs: List<SpeedRun>,
    /** Median over runs. */
    @SerialName("down_mbps") val downMbps: Double? = null,
    @SerialName("up_mbps") val upMbps: Double? = null,
    @SerialName("ping_ms") val pingMs: Double? = null,
    @SerialName("jitter_ms") val jitterMs: Double? = null,
)

@Serializable
data class ServingCell(
    @SerialName("net_type") val netType: NetType,
    val band: Int? = null,
    val pci: Int? = null,
    @SerialName("cell_id") val cellId: Long? = null,
    val earfcn: Int? = null,
    val ta: Int? = null,
)

@Serializable
data class SpotMetrics(
    val score: MetricStats,
    val rsrp: MetricStats,
    val sinr: MetricStats? = null,
    val rsrq: MetricStats? = null,
)

/** A saved spot test (plan 7.3 "Spot test"), optionally with speed tests and the baseline flag. */
@Serializable
data class FinderSpot(
    /** "s_" + random, generated by the Agent. */
    val id: String,
    val name: String,
    @SerialName("created_at") val createdAt: String,
    @SerialName("duration_s") val durationS: Int,
    val lat: Double? = null,
    val lon: Double? = null,
    @SerialName("acc_m") val accM: Double? = null,
    @SerialName("compass_deg") val compassDeg: Double? = null,
    /** "upright" | "flat" | "rot90" | free text */
    val orientation: String? = null,
    @SerialName("pitch_deg") val pitchDeg: Double? = null,
    @SerialName("roll_deg") val rollDeg: Double? = null,
    /** The photo stays on the phone. */
    @SerialName("has_photo") val hasPhoto: Boolean? = null,
    val serving: ServingCell,
    /** Serving-cell changes during the test (plan 7.5 flag). */
    @SerialName("cell_switches") val cellSwitches: Int,
    val metrics: SpotMetrics,
    val speed: List<SpeedSession> = emptyList(),
    /** The installed spot (plan 7.3 "Baseline"). */
    val baseline: Boolean = false,
) {
    /** Best measured download speed across sessions, or null (finder.ts `spotBestDown`). */
    val bestDownMbps: Double? get() = speed.mapNotNull { it.downMbps }.maxOrNull()
}

/** Plan 7.3 "Ranking": measured speed first, score second (finder.ts `rankSpots`). */
fun rankSpots(spots: List<FinderSpot>): List<FinderSpot> = spots.sortedWith { a, b ->
    val sa = a.bestDownMbps
    val sb = b.bestDownMbps
    when {
        sa != null && sb != null && sa != sb -> sb.compareTo(sa)
        sa != null && sb == null -> -1
        sa == null && sb != null -> 1
        else -> b.metrics.score.avg.compareTo(a.metrics.score.avg)
    }
}
