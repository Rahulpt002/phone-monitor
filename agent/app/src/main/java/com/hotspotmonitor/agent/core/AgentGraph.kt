/** Why the Agent service started (event `agent_start` data.reason). */
enum class AgentStartReason(val wire: String) {
    BOOT("boot"),
    RESTART("restart"),
    UPDATE("update"),
    MANUAL("manual"),
}

/**
 * Manual service locator: every singleton of the Agent, created by [AgentApp] once per process.
 * Everything is lazy, so construction order never matters and unit-test-free Android pieces are
 * only touched when used. Module implementations take `(graph: AgentGraph)` and read what they
 * need from it; they never construct each other.
 *
 * Integrator-owned (see ARCHITECTURE.md). Module builders do not edit this file.
 */
class AgentGraph(context: Context) {
    val app: Context = context.applicationContext

    val log: AgentLog = AgentLog(File(app.filesDir, "logs"))

    private val crashHandler = CoroutineExceptionHandler { _, error -> reportUncaught("coroutine", error) }

    /** Process-wide scope (outbox, events, profile follow). Never cancelled. */
    val appScope: CoroutineScope = CoroutineScope(SupervisorJob() + Dispatchers.Default + crashHandler)

    val clock: Clock = Clock()

    val prefs: KeyValueStore by lazy { SharedPrefsStore(app.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)) }

    val db: AgentDatabase by lazy { AgentDatabase.build(app) }

    val outbox: OutboxStore by lazy { OutboxStore(db.outboxDao(), clock, log, appScope) }

    val events: EventSink by lazy { EventSink(outbox, clock, log, appScope) }

    val settings: SettingsRepo by lazy {
        SettingsRepo(prefs, log) { version ->
            events.emit(
                EventKind.SETTINGS_APPLIED, Severity.INFO, "Applied settings version $version",
                jsonObjectOf("version" to version),
            )
        }
    }

    val secureStore: SecureStore by lazy { SecureStore(prefs, KeystoreCrypter(TOKEN_KEY_ALIAS), log) }

    val pairingState: PairingState by lazy { PairingState(prefs, secureStore, log) }

    val shell: RootShell by lazy { LibsuRootShell(log) }

    val profiles: ProfileRepo by lazy {
        ProfileRepo(AssetProfileSource(app.assets), settings.settings, log, Build.MANUFACTURER, Build.MODEL)
    }

    val rootSetup: RootSetup by lazy { RootSetup(app, shell, prefs, log, BuildConfig.VERSION_CODE) }

    /**
     * Shared HTTP client. Derive per-use clients with `http.newBuilder()` (they share the
     * connection pool and dispatcher) instead of creating new ones.
     */
    val http: OkHttpClient by lazy {
        OkHttpClient.Builder()
            .connectTimeout(15, TimeUnit.SECONDS)
            .readTimeout(30, TimeUnit.SECONDS)
            .writeTimeout(30, TimeUnit.SECONDS)
            .retryOnConnectionFailure(true)
            .build()
    }

    // --- modules (one implementation each; see core/Modules.kt) --------------------------------

    val telemetry: TelemetryHub by lazy { TelemetryHubImpl(this) }
    val commands: CommandExecutor by lazy { CommandExecutorImpl(this) }
    val controls: Controls by lazy { ControlsImpl(this) }
    val charge: ChargeController by lazy { ChargeControllerImpl(this) }
    val rebootLimiter: RebootLimiter by lazy { RebootLimiterImpl(this) }
    val watchdog: Watchdog by lazy { WatchdogImpl(this) }
    val finder: FinderEngine by lazy { FinderEngineImpl(this) }
    val sync: SyncClient by lazy { SyncClientImpl(this) }

    /** Pairing over HTTP (PairActivity, PairingScreen). Persistent state is [pairingState]. */
    val pairing: PairingClient by lazy { PairingClientImpl(this) }

    // --- service lifecycle ---------------------------------------------------------------------

    val agentVersion: String = BuildConfig.VERSION_NAME
    val agentVersionCode: Int = BuildConfig.VERSION_CODE

    private val _running = MutableStateFlow(false)

    /** True between [startAll] and [stopAll]. */
    val running: StateFlow<Boolean> = _running.asStateFlow()

    @Volatile
    private var startedAtElapsedMs: Long? = null

    /** Seconds since the service started the modules (heartbeat `agent_uptime_s`), 0 when stopped. */
    fun agentUptimeS(): Long = startedAtElapsedMs?.let { (clock.elapsedMs() - it) / 1000 } ?: 0

    private var serviceScope: CoroutineScope? = null

    /**
     * Starts every module (called by AgentService). Idempotent: returns false when already running.
     * Order: root setup (background) and profiles, then telemetry (so the watchdog, charge and
     * Finder find readings early), charge, commands, watchdog, finder, sync, and finally the
     * `agent_start` event.
     */
    @Synchronized
    fun startAll(reason: AgentStartReason): Boolean {
        if (serviceScope != null) return false
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default + crashHandler)
        serviceScope = scope
        startedAtElapsedMs = clock.elapsedMs()
        log.i(TAG, "Starting Agent $agentVersion ($reason) on ${Build.MANUFACTURER} ${Build.MODEL}, SDK ${Build.VERSION.SDK_INT}")

        scope.launch(Dispatchers.IO) {
            runCatching { rootSetup.ensure() }.onFailure { log.e(TAG, "Root setup failed", it) }
        }
        runCatching { profiles.start(scope) }.onFailure { log.e(TAG, "Profile repo failed to start", it) }
        for ((name, module) in modulesInStartOrder()) {
            try {
                module.start(scope)
            } catch (e: Exception) {
                reportUncaught("start:$name", e)
            }
        }
        _running.value = true
        events.emit(
            EventKind.AGENT_START, Severity.INFO, "Agent $agentVersion started (${reason.wire})",
            jsonObjectOf("reason" to reason.wire, "agent_version" to agentVersion),
        )
        return true
    }

    /** Stops every module (AgentService.onDestroy). Safe to call when not running. */
    @Synchronized
    fun stopAll() {
        val scope = serviceScope ?: return
        log.i(TAG, "Stopping Agent")
        scope.cancel()
        for ((name, module) in modulesInStartOrder().asReversed()) {
            try {
                module.stop()
            } catch (e: Exception) {
                log.w(TAG, "Module $name failed to stop cleanly", e)
            }
        }
        serviceScope = null
        startedAtElapsedMs = null
        _running.value = false
        log.flush()
    }

    private fun modulesInStartOrder(): List<Pair<String, AgentModule>> = listOf(
        "telemetry" to telemetry,
        "charge" to charge,
        "commands" to commands,
        "watchdog" to watchdog,
        "finder" to finder,
        "sync" to sync,
    )

    private fun reportUncaught(where: String, error: Throwable) {
        log.e(TAG, "Unexpected error in $where", error)
        runCatching {
            events.emit(
                EventKind.ERROR, Severity.WARNING, "Unexpected error in $where: ${error.javaClass.simpleName}",
                jsonObjectOf("where" to where, "message" to (error.message ?: error.javaClass.simpleName).take(500)),
            )
        }
    }

    companion object {
        private const val TAG = "graph"
        const val PREFS_NAME = "agent"
        const val TOKEN_KEY_ALIAS = "hsm_device_token_key"
    }
}
