/**
 * Events (plan 6.2 "Events" row, and the watchdog log in 6.5). Sent immediately by the Agent,
 * buffered while offline, stored by the Server, shown in the Dashboard timeline, and some
 * kinds raise alerts (see `EVENT_ALERT` below and plan 8.5).
 */
import type { AlertKind } from './settings.js';

export type EventKind =
  | 'agent_start' // service started; data: { reason: 'boot' | 'restart' | 'update' | 'manual' }
  | 'boot' // phone booted; data: { boot_count, boot_reason }
  | 'connectivity' // internet up/down; data: { online: boolean, down_for_s? }
  | 'cell_change' // serving cell changed; data: { from: {pci, cell_id, band}, to: {...} }
  | 'net_type_change' // e.g. LTE -> NR_NSA
  | 'tether_up'
  | 'tether_down'
  | 'usb_connected'
  | 'usb_disconnected'
  | 'power_connected'
  | 'power_lost' // USB power removed (plan 6.5 "USB power lost")
  | 'weak_power' // plugged in but battery falling for weak_power_min
  | 'temp_warning' // battery >= temp_warn_c
  | 'temp_critical' // battery >= temp_stop_charge_c (charging stopped)
  | 'temp_normal' // back below temp_resume_c
  | 'charging_stopped' // data: { reason: 'limit' | 'heat' | 'manual' }
  | 'charging_resumed'
  | 'radio_rest' // data: { seconds }
  // data: { rule: 'internet'|'tether'|'schedule', action: 'data_cycle'|'airplane_cycle'|'reboot'|'usb_tethering',
  //         step, outcome: 'recovered'|'still_down'|'rebooting'|'blocked' }
  | 'watchdog_action'
  | 'command' // Agent-local command executed (local UI / watchdog); data: CommandRecord-like
  | 'revert' // auto-revert happened; data: { command_id, name }
  | 'moved' // tilt or location changed; data: { tilt_change_deg, moved_m, lat, lon }
  | 'sms_received' // data: { from, body, at }
  | 'reboot_blocked' // reboot limit reached; data: { source }
  | 'settings_applied' // Agent applied a new settings version; data: { version }
  | 'finder' // spot test / speed test finished; data: { spot_id }
  | 'error'; // unexpected Agent error; data: { where, message }

export type Severity = 'info' | 'warning' | 'critical';

export interface AgentEvent {
  id: string; // "e_" + random, generated by the Agent; the Server ignores duplicates
  ts: string;
  kind: EventKind;
  severity: Severity;
  message: string; // short human-readable line
  data?: Record<string, unknown>;
}

/** Events that raise an alert directly (the rest are only logged). */
export const EVENT_ALERT: Partial<Record<EventKind, AlertKind>> = {
  weak_power: 'weak_power',
  temp_warning: 'hot',
  temp_critical: 'hot',
  power_lost: 'usb_power_lost',
  moved: 'moved',
  watchdog_action: 'watchdog',
  revert: 'watchdog',
  reboot_blocked: 'watchdog',
  sms_received: 'carrier_sms',
};
