/**
 * Signal Finder (plan section 7). The Agent computes the score; the Dashboard and Server
 * use the same formula for display, baseline comparison and tests. The Kotlin Agent mirrors
 * `signalScore` exactly (see docs/protocol.md "Score") and is unit-tested against
 * shared/fixtures/score-cases.json.
 */
import type { NetType } from './telemetry.js';

export const clamp = (v: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, v));

export interface ScoreWeights {
  w_sinr: number;
  w_rsrp: number;
  w_rsrq: number;
}

export const DEFAULT_WEIGHTS: ScoreWeights = { w_sinr: 0.45, w_rsrp: 0.35, w_rsrq: 0.2 };

/**
 * score = 100 * (0.45 * n_sinr + 0.35 * n_rsrp + 0.20 * n_rsrq), rounded to 1 decimal.
 * Returns null when RSRP is missing. A missing SINR or RSRQ counts as 0 for that term
 * (the reading is incomplete, so the score errs low).
 */
export function signalScore(
  rsrp: number | null | undefined,
  sinr: number | null | undefined,
  rsrq: number | null | undefined,
  w: ScoreWeights = DEFAULT_WEIGHTS,
): number | null {
  if (rsrp == null || Number.isNaN(rsrp)) return null;
  const nRsrp = clamp((rsrp + 120) / 40, 0, 1);
  const nSinr = sinr == null || Number.isNaN(sinr) ? 0 : clamp((sinr + 5) / 30, 0, 1);
  const nRsrq = rsrq == null || Number.isNaN(rsrq) ? 0 : clamp((rsrq + 20) / 12, 0, 1);
  const s = 100 * (w.w_sinr * nSinr + w.w_rsrp * nRsrp + w.w_rsrq * nRsrq);
  return Math.round(s * 10) / 10;
}

export type Grade = 'excellent' | 'good' | 'fair' | 'poor';

/** Plan 7.1 thresholds. Boundary values belong to the better grade ("above -80" -> -80 is good). */
export function gradeRsrp(v: number): Grade {
  return v > -80 ? 'excellent' : v >= -90 ? 'good' : v >= -100 ? 'fair' : 'poor';
}
export function gradeSinr(v: number): Grade {
  return v > 20 ? 'excellent' : v >= 13 ? 'good' : v >= 0 ? 'fair' : 'poor';
}
export function gradeRsrq(v: number): Grade {
  return v > -10 ? 'excellent' : v >= -15 ? 'good' : v >= -20 ? 'fair' : 'poor';
}
export function gradeScore(v: number): Grade {
  return v >= 75 ? 'excellent' : v >= 55 ? 'good' : v >= 35 ? 'fair' : 'poor';
}

export type FinderMode = 'idle' | 'walk' | 'spot' | 'speed' | 'headless';

/** Streamed 1/s while a Dashboard has the Finder screen open (plan 7.3 "Mirror"). Not stored. */
export interface FinderLive {
  ts: string;
  mode: FinderMode;
  score: number | null; // smoothed
  score_raw: number | null;
  rsrp?: number | null;
  sinr?: number | null;
  rsrq?: number | null;
  net_type?: NetType;
  band?: number | null;
  pci?: number | null;
  cell_id?: number | null;
  ta?: number | null;
  cell_switches_5min?: number; // serving-cell changes in the last 5 minutes (plan 7.5)
  progress?: { label: string; elapsed_s: number; total_s: number } | null; // spot / speed test
}

export interface MetricStats {
  avg: number;
  min: number;
  max: number;
  std: number; // stability: lower is steadier
  samples: number;
}

export interface SpeedRun {
  down_mbps: number | null;
  up_mbps: number | null;
  ping_ms: number | null;
  jitter_ms: number | null;
  bytes: number; // total data used by this run
  at: string;
}

export interface SpeedSession {
  at: string;
  peak_hour: boolean; // started between 20:00 and 22:00 phone local time (plan 7.4 step 4)
  runs: SpeedRun[];
  down_mbps: number | null; // median over runs
  up_mbps: number | null;
  ping_ms: number | null;
  jitter_ms: number | null;
}

/** A saved spot test (plan 7.3 "Spot test"), optionally with speed tests and the baseline flag. */
export interface FinderSpot {
  id: string; // "s_" + random, generated by the Agent
  name: string;
  created_at: string;
  duration_s: number;
  lat?: number | null;
  lon?: number | null;
  acc_m?: number | null;
  compass_deg?: number | null;
  orientation?: string | null; // "upright" | "flat" | "rot90" | free text
  pitch_deg?: number | null;
  roll_deg?: number | null;
  has_photo?: boolean; // the photo stays on the phone
  serving: { net_type: NetType; band?: number | null; pci?: number | null; cell_id?: number | null; earfcn?: number | null; ta?: number | null };
  cell_switches: number; // serving-cell changes during the test (plan 7.5 flag)
  metrics: {
    score: MetricStats;
    rsrp: MetricStats;
    sinr?: MetricStats | null;
    rsrq?: MetricStats | null;
  };
  speed: SpeedSession[];
  baseline: boolean; // the installed spot (plan 7.3 "Baseline")
}

/** Best measured download speed across sessions, or null. */
export function spotBestDown(s: FinderSpot): number | null {
  const v = s.speed.map((x) => x.down_mbps).filter((x): x is number => x != null);
  return v.length ? Math.max(...v) : null;
}

/** Plan 7.3 "Ranking": measured speed first, score second. Spots without speed rank after those with. */
export function rankSpots(spots: FinderSpot[]): FinderSpot[] {
  return [...spots].sort((a, b) => {
    const sa = spotBestDown(a);
    const sb = spotBestDown(b);
    if (sa != null && sb != null && sa !== sb) return sb - sa;
    if (sa != null && sb == null) return -1;
    if (sa == null && sb != null) return 1;
    return b.metrics.score.avg - a.metrics.score.avg;
  });
}
